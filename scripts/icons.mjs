// Renders every icon RigReady ships from the brand masters in assets/brand:
//
//   npm run icons
//
// The masters are assets/brand/rigready.svg (48 px and more) and rigready-small.svg (32 px
// and less: heavier strokes, so the mark still reads at 16 px). From them:
//
//   assets/icon.ico              the exe, window, tray, installer and shortcut icon
//                                (16, 20, 24, 32 small; 48, 64, 128, 256 master)
//   assets/icon.png              512 px, for anything that wants a plain picture
//   assets/tray-16.png           the tray's mark at the two sizes Windows draws it;
//   assets/tray-32.png           the 32 is the base the status badge is painted on
//   build/installerSidebar.bmp   the left panel of the installer's welcome and finish pages
//   site/favicon.svg             a copy of the small master for the website
//
// It runs under Electron (`electron scripts/icons.mjs`), the one renderer the repository
// already has: a hidden window draws each SVG onto a canvas at the exact pixel size, so
// every file is a true rasterisation of the master and not a resample of a bigger one.
// Nothing outside the repository is written: Electron's own data goes to
// node_modules/.cache/rigready-icons.
import { app, BrowserWindow } from 'electron';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const brand = path.join(root, 'assets', 'brand');

/** The sizes in the .ico, and which master each comes from. */
const ICO_SIZES = [16, 20, 24, 32, 48, 64, 128, 256];
const SMALL_UP_TO = 32;
/** The MUI welcome page bitmap, at the size NSIS expects (164 x 314 at 96 dpi). */
const SIDEBAR = { width: 164, height: 314 };

app.setPath('userData', path.join(root, 'node_modules', '.cache', 'rigready-icons'));
app.setPath('sessionData', path.join(root, 'node_modules', '.cache', 'rigready-icons'));
app
  .whenReady()
  .then(main)
  .then(
    () => app.exit(0),
    (e) => {
      console.error(e);
      app.exit(1);
    }
  );

async function main() {
  const master = await readFile(path.join(brand, 'rigready.svg'), 'utf8');
  const small = await readFile(path.join(brand, 'rigready-small.svg'), 'utf8');
  const svgFor = (size) => (size <= SMALL_UP_TO ? small : master);

  const window = new BrowserWindow({
    show: false,
    webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false },
  });
  try {
    await window.loadURL('about:blank');
    const page = (script) => window.webContents.executeJavaScript(script, true);

    const renders = new Map();
    for (const size of ICO_SIZES) renders.set(size, await render(page, svgFor(size), size));
    const png512 = await render(page, master, 512);

    await write('assets/icon.ico', ico(ICO_SIZES.map((size) => [size, renders.get(size)])));
    await write('assets/icon.png', png512.png);
    await write('assets/tray-16.png', renders.get(16).png);
    await write('assets/tray-32.png', renders.get(32).png);
    await write('build/installerSidebar.bmp', bmp(await sidebar(page, master)));
    await write(
      'site/favicon.svg',
      small.replace(
        /<!--[\s\S]*?-->\n/,
        '<!-- Generated by scripts/icons.mjs from assets/brand/rigready-small.svg; edit that file. -->\n'
      )
    );
  } finally {
    window.destroy();
  }
}

async function write(file, bytes) {
  const target = path.join(root, file);
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, bytes);
  console.log(`${file}: ${bytes.length} bytes`);
}

/** The SVG with its root sized to `size`, so the browser rasterises it at exactly that. */
function sized(svg, width, height) {
  return svg.replace(
    /<svg\b([^>]*)>/,
    (_, attrs) =>
      `<svg${attrs.replace(/\s(width|height)="[^"]*"/g, '')} width="${width}" height="${height}">`
  );
}

/** Page-side helper: a Uint8Array as base64, in pieces (one call per byte would be slow). */
const TO_BASE64 = `
  const toBase64 = (bytes) => {
    let text = '';
    for (let i = 0; i < bytes.length; i += 8192) {
      text += String.fromCharCode.apply(null, bytes.subarray(i, i + 8192));
    }
    return btoa(text);
  };
  const loaded = async (svg) => {
    const img = new Image();
    img.src = 'data:image/svg+xml;base64,' + btoa(unescape(encodeURIComponent(svg)));
    await img.decode();
    return img;
  };
`;

/**
 * The SVG drawn at `size` x `size`: the PNG the browser encodes and the raw straight-alpha
 * RGBA pixels (top row first), for the formats that want them.
 */
async function render(page, svg, size) {
  const result = await page(`(async () => {
    ${TO_BASE64}
    const img = await loaded(${JSON.stringify(sized(svg, size, size))});
    const canvas = document.createElement('canvas');
    canvas.width = ${size};
    canvas.height = ${size};
    const ctx = canvas.getContext('2d');
    ctx.drawImage(img, 0, 0, ${size}, ${size});
    return {
      png: canvas.toDataURL('image/png').split(',')[1],
      rgba: toBase64(ctx.getImageData(0, 0, ${size}, ${size}).data),
    };
  })()`);
  return {
    width: size,
    height: size,
    png: Buffer.from(result.png, 'base64'),
    rgba: Buffer.from(result.rgba, 'base64'),
  };
}

/** The installer's sidebar: the mark on the app's background, with the name under it. */
async function sidebar(page, master) {
  const { width, height } = SIDEBAR;
  const tile = 88;
  const result = await page(`(async () => {
    ${TO_BASE64}
    const img = await loaded(${JSON.stringify(sized(master, tile, tile))});
    const canvas = document.createElement('canvas');
    canvas.width = ${width};
    canvas.height = ${height};
    const ctx = canvas.getContext('2d');
    ctx.fillStyle = '#0f1317';
    ctx.fillRect(0, 0, ${width}, ${height});
    ctx.drawImage(img, ${(width - tile) / 2}, 52, ${tile}, ${tile});
    ctx.fillStyle = '#ede9e6';
    ctx.font = '600 21px "Segoe UI", "Segoe UI Variable", sans-serif';
    ctx.textAlign = 'center';
    ctx.textBaseline = 'alphabetic';
    ctx.fillText('RigReady', ${width / 2}, 52 + ${tile} + 40);
    ctx.fillStyle = '#5aa9e6';
    ctx.fillRect(${width / 2 - 14}, 52 + ${tile} + 58, 28, 2);
    return toBase64(ctx.getImageData(0, 0, ${width}, ${height}).data);
  })()`);
  return { width, height, rgba: Buffer.from(result, 'base64') };
}

/**
 * A Windows icon: every entry a 32-bit bitmap. Windows would also take the 256 px entry as
 * PNG (a quarter of the bytes), but GDI+ and older tools would not, and the file only
 * lives inside the exe.
 */
function ico(entries) {
  const images = entries.map(([, image]) => dib(image.width, image.height, image.rgba));
  const header = Buffer.alloc(6 + 16 * entries.length);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(entries.length, 4);
  let offset = header.length;
  entries.forEach(([size], index) => {
    const at = 6 + index * 16;
    header.writeUInt8(size >= 256 ? 0 : size, at);
    header.writeUInt8(size >= 256 ? 0 : size, at + 1);
    header.writeUInt8(0, at + 2);
    header.writeUInt8(0, at + 3);
    header.writeUInt16LE(1, at + 4);
    header.writeUInt16LE(32, at + 6);
    header.writeUInt32LE(images[index].length, at + 8);
    header.writeUInt32LE(offset, at + 12);
    offset += images[index].length;
  });
  return Buffer.concat([header, ...images]);
}

/** A 32-bit icon bitmap: BITMAPINFOHEADER, BGRA rows bottom-up, then the 1-bit mask. */
function dib(width, height, rgba) {
  const maskStride = Math.ceil(width / 32) * 4;
  const xor = Buffer.alloc(width * height * 4);
  const mask = Buffer.alloc(maskStride * height);
  for (let y = 0; y < height; y++) {
    const row = height - 1 - y;
    for (let x = 0; x < width; x++) {
      const i = (y * width + x) * 4;
      const o = (row * width + x) * 4;
      xor[o] = rgba[i + 2];
      xor[o + 1] = rgba[i + 1];
      xor[o + 2] = rgba[i];
      xor[o + 3] = rgba[i + 3];
      if (rgba[i + 3] === 0) mask[row * maskStride + (x >> 3)] |= 0x80 >> (x & 7);
    }
  }
  const header = Buffer.alloc(40);
  header.writeUInt32LE(40, 0);
  header.writeInt32LE(width, 4);
  header.writeInt32LE(height * 2, 8);
  header.writeUInt16LE(1, 12);
  header.writeUInt16LE(32, 14);
  header.writeUInt32LE(0, 16);
  header.writeUInt32LE(xor.length + mask.length, 20);
  return Buffer.concat([header, xor, mask]);
}

/** A 24-bit BMP file (what NSIS wants), from straight-alpha RGBA on an opaque picture. */
function bmp({ width, height, rgba }) {
  const stride = Math.ceil((width * 3) / 4) * 4;
  const pixels = Buffer.alloc(stride * height);
  for (let y = 0; y < height; y++) {
    const row = height - 1 - y;
    for (let x = 0; x < width; x++) {
      const i = (y * width + x) * 4;
      const o = row * stride + x * 3;
      pixels[o] = rgba[i + 2];
      pixels[o + 1] = rgba[i + 1];
      pixels[o + 2] = rgba[i];
    }
  }
  const header = Buffer.alloc(54);
  header.write('BM', 0, 'ascii');
  header.writeUInt32LE(54 + pixels.length, 2);
  header.writeUInt32LE(54, 10);
  header.writeUInt32LE(40, 14);
  header.writeInt32LE(width, 18);
  header.writeInt32LE(height, 22);
  header.writeUInt16LE(1, 26);
  header.writeUInt16LE(24, 28);
  header.writeUInt32LE(pixels.length, 34);
  header.writeInt32LE(3780, 38);
  header.writeInt32LE(3780, 42);
  return Buffer.concat([header, pixels]);
}
